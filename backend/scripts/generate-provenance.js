'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {INTEGRITY_EXCLUSIONS,collectFiles}=require('./provenance-files');
const root=path.resolve(__dirname,'..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const manifestPath=path.join(root,'SALES_PACKAGE_MANIFEST.json');
const sha=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const files=collectFiles(root).map(relativePath=>{const file=path.join(root,relativePath);return{path:relativePath,sha256:sha(file),bytes:fs.statSync(file).size};});
const manifest={product:'OpsCore Operational SaaS Starter Kit',version:pkg.version,generatedAt:new Date().toISOString(),integrityExclusions:[...INTEGRITY_EXCLUSIONS],files};
fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
const lines=files.map(x=>`${x.sha256}  ${x.path}`).join('\n')+'\n';
for(const name of ['RELEASE_FILE_SHA256SUMS.txt','RELEASE_COMPONENT_SHA256SUMS.txt'])fs.writeFileSync(path.join(root,name),lines);
console.log(`Generated provenance for ${files.length} backend files at v${pkg.version}`);
